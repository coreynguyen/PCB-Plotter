#pragma once
// ============================================================================
// gencad.h — GenCAD 1.4 import / export (pcbp::io).
//
// Import: $HEADER (UNITS INCH|MM|THOU|MIL|USER n|USERM n|USERMM n, ORIGIN),
// $BOARD (LINE/ARC/CIRCLE/RECTANGLE outline -> Project::board_frame, arcs
// approximated and chained into polylines), $PADS, $PADSTACKS, $SHAPES
// (-> Package: PIN pads, LINE/ARC/CIRCLE/RECTANGLE body artwork, INSERT,
// HEIGHT, FIDUCIAL), $COMPONENTS (-> Component), $DEVICES (-> PartNumber),
// $SIGNALS (optional nets). $ROUTES, $MECH, $TRACKS, $LAYERS... are skipped.
//
// Export reproduces the dialect CircuitCAM itself writes (see CCDemo.cad):
// INCH units, 4 decimals, CRLF, blank line between sections, pads named
// Pad<n> with drill -1, RECTANGLE as "x y w h", SHAPE "<name> 0 0" for top,
// devices with PART/PACKAGE/PINCOUNT/DESC.
// ============================================================================
#include "../core/project.h"
#include <string>
#include <vector>
#include <utility>

namespace pcbp::io {

struct GencadOptions {
    bool replace = true;                // clear comps/packages/parts/board first
    bool import_board = true;
    bool import_packages = true;        // otherwise only components
    bool fiducial_by_name = true;       // refs "FID*" -> Feature::Fiducial
    double arc_seg_deg = 10.0;          // board arc approximation step
    bool overwrite_packages = true;     // replace same-named packages in the project
};

struct GencadNet {
    std::string name;
    std::vector<std::pair<std::string, std::string>> nodes;   // (ref, pin)
};

struct GencadResult {
    std::string version, user, drawing, revision, units;
    double unit_mm = 25.4;
    int pads = 0, padstacks = 0, shapes = 0, components = 0, devices = 0;
    int fiducials = 0, board_items = 0, board_polylines = 0;
    std::vector<GencadNet> nets;
    std::vector<std::string> skipped_sections;
    std::vector<std::string> warnings;
    std::string describe() const;
};

bool import_gencad_text(const std::string& text, Project& prj, const GencadOptions& opt,
                        GencadResult& res, std::string& err);
bool import_gencad_file(const std::string& path, Project& prj, const GencadOptions& opt,
                        GencadResult& res, std::string& err);

enum class SideFilter { Top, Bottom, Both };

struct GencadExportOptions {
    SideFilter side = SideFilter::Both;
    std::vector<int> model_points;      // only comps assigned to these points; empty = all
    bool include_board = true;
    bool include_fiducials = true;
    bool crlf = true;
    std::string user = "Generated by PCB Plotter";
    int decimals = 4;
};

bool export_gencad(const Project& prj, const GencadExportOptions& opt,
                   std::string& out, std::string& err);

} // namespace pcbp::io
